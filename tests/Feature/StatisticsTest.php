    protected function defineEnvironment($app): void
    {
        parent::defineEnvironment($app);

        $app['config']->set('filament-mailbox.statistics.enabled', true);
        $app['config']->set('filament-mailbox.statistics.live_cache_seconds', 0);
        $app['config']->set('app.timezone', 'UTC');
    }

    protected function setUp(): void
    {
        parent::setUp();

        $this->travelTo(CarbonImmutable::parse('2026-09-16 12:00:00', 'UTC'));

        $this->mailbox = Mailbox::factory()->create(['name' => 'Support', 'business_hours' => ['timezone' => 'Europe/Berlin']]);
        $this->inbox = MailboxFolder::factory()->inbox()->create(['mailbox_id' => $this->mailbox->id]);
        $this->sent = MailboxFolder::factory()->specialUse(SpecialUse::Sent)->create(['mailbox_id' => $this->mailbox->id, 'name' => 'Sent', 'full_name' => 'Sent']);
    }

    protected function inbound(string $receivedAt, array $attributes = []): MailboxMessage
    {
        return MailboxMessage::factory()->create([
            'folder_id' => $this->inbox->id,
            'received_at' => $receivedAt,
            'sent_at' => $receivedAt,
            ...$attributes,
        ]);
    }

    protected function reply(MailboxMessage $to, string $sentAt, array $attributes = []): MailboxMessage
    {
        return MailboxMessage::factory()->create([
            'folder_id' => $this->sent->id,
            'in_reply_to' => $to->message_id,
            'sent_at' => $sentAt,
            'received_at' => $sentAt,
            ...$attributes,
        ]);
    }

    public function test_automatically_generated_mail_is_detected_from_headers(): void
    {
        $raw = fn (string $headers): string => "Message-ID: <a@example.com>\r\nFrom: a@example.com\r\nTo: b@example.com\r\nSubject: Hi\r\n{$headers}Content-Type: text/plain\r\n\r\nHello";

        $this->assertFalse(MimeMessageMapper::fromRaw($raw(''), '1')->isAutoGenerated);
        $this->assertFalse(MimeMessageMapper::fromRaw($raw("Auto-Submitted: no\r\n"), '1')->isAutoGenerated);
        $this->assertTrue(MimeMessageMapper::fromRaw($raw("Auto-Submitted: auto-replied\r\n"), '1')->isAutoGenerated);
        $this->assertTrue(MimeMessageMapper::fromRaw($raw("Precedence: bulk\r\n"), '1')->isAutoGenerated);
        $this->assertTrue(MimeMessageMapper::fromRaw($raw("List-Id: <news.example.com>\r\n"), '1')->isAutoGenerated);

        $message = app(SyncService::class)->importMessage($this->inbox, new MessageData(remoteId: '99', messageId: '<auto@example.com>', isAutoGenerated: true));
        $this->assertTrue($message);
        $this->assertTrue(MailboxMessage::where('message_id', '<auto@example.com>')->sole()->is_auto_generated);
    }

    public function test_replies_are_linked_by_in_reply_to_and_references(): void
    {
        $linker = app(ReplyLinker::class);
        $inbound = $this->inbound('2026-09-15 08:00:00');
        $reply = $this->reply($inbound, '2026-09-15 09:30:00');

        $this->assertCount(1, $linker->linkReply($reply));
        $this->assertSame(90, (int) DB::table('mailbox_reply_links')->value('reply_minutes'));
        // Idempotent.
        $this->assertCount(0, $linker->linkReply($reply));

        $other = $this->inbound('2026-09-15 08:00:00');
        $viaReferences = $this->reply($other, '2026-09-15 10:00:00', ['in_reply_to' => null, 'references' => '<root@example.com> '.$other->message_id]);
        $this->assertCount(1, $linker->linkReply($viaReferences));

        // A message of another mailbox with the same Message-ID is never linked.
        $foreign = MailboxMessage::factory()->create(['message_id' => '<foreign@example.com>', 'received_at' => '2026-09-15 08:00:00']);
        $this->assertCount(0, $linker->linkReply($this->reply($foreign, '2026-09-15 09:00:00')));

        // Replies dated before the original are ignored.
        $late = $this->inbound('2026-09-15 12:00:00');
        $this->assertCount(0, $linker->linkReply($this->reply($late, '2026-09-15 11:00:00')));
    }

    public function test_the_import_links_replies_in_both_orders_and_the_earliest_reply_counts(): void
    {
        $sync = app(SyncService::class);

        // The reply is imported before the message it answers.
        $sync->importMessage($this->sent, new MessageData(remoteId: '1', messageId: '<r1@example.com>', inReplyTo: '<in@example.com>', sentAt: CarbonImmutable::parse('2026-09-15 12:00:00')));
        $sync->importMessage($this->inbox, new MessageData(remoteId: '1', messageId: '<in@example.com>', from: new \Cooolinho\FilamentMailbox\Data\AddressData('c@customer.test'), sentAt: CarbonImmutable::parse('2026-09-15 08:00:00'), receivedAt: CarbonImmutable::parse('2026-09-15 08:00:00')));
        $sync->importMessage($this->sent, new MessageData(remoteId: '2', messageId: '<r2@example.com>', inReplyTo: '<in@example.com>', sentAt: CarbonImmutable::parse('2026-09-15 09:00:00')));

        $this->assertSame(2, DB::table('mailbox_reply_links')->count());
        // Imports into already finished days mark them for recalculation.
        $this->assertTrue(DB::table('mailbox_stats_dirty_days')->where('mailbox_id', $this->mailbox->id)->where('date', '2026-09-15')->exists());

        $row = app(DailyStatsAggregator::class)->aggregate($this->mailbox, '2026-09-15');

        $this->assertSame(1, $row['replied_count']);
        $this->assertSame(60, $row['reply_minutes_p50']);
        $this->assertFalse(DB::table('mailbox_stats_dirty_days')->exists());
    }

    public function test_business_hours_are_counted_across_nights_weekends_holidays_and_dst(): void
    {
        $calculator = app(BusinessHoursCalculator::class);
        $hours = BusinessHours::fromArray([
            'hours' => array_map(fn (string $day): array => ['day' => $day, 'start' => '08:00', 'end' => '17:00'], ['mon', 'tue', 'wed', 'thu', 'fri']),
            'holidays' => ['2026-10-05'],
        ], 'Europe/Berlin');

        $at = fn (string $local): CarbonImmutable => CarbonImmutable::parse($local, 'Europe/Berlin');

        // Tuesday 16:00 → Wednesday 09:00: one hour each day.
        $this->assertSame(120, $calculator->minutes($at('2026-09-15 16:00'), $at('2026-09-16 09:00'), $hours));
        // Friday 16:30 → Monday 08:30 skips the weekend.
        $this->assertSame(60, $calculator->minutes($at('2026-09-18 16:30'), $at('2026-09-21 08:30'), $hours));
        // Friday 16:00 → Tuesday 09:00 with Monday as holiday.
        $this->assertSame(120, $calculator->minutes($at('2026-10-02 16:00'), $at('2026-10-06 09:00'), $hours));
        // Before opening, within the same day, reversed.
        $this->assertSame(0, $calculator->minutes($at('2026-09-15 06:00'), $at('2026-09-15 07:59'), $hours));
        $this->assertSame(0, $calculator->minutes($at('2026-09-15 12:00'), $at('2026-09-15 10:00'), $hours));
        // DST ends on Sunday 2026-10-25: Friday 16:00 → Monday 09:00 is still two business hours.
        $this->assertSame(120, $calculator->minutes($at('2026-10-23 16:00'), $at('2026-10-26 09:00'), $hours));
        // A 24/7 schedule across the DST switch counts real elapsed time (25 h).
        $always = BusinessHours::fromArray(['hours' => array_map(fn (string $day): array => ['day' => $day, 'start' => '00:00', 'end' => '23:59'], BusinessHours::DAYS)], 'Europe/Berlin');
        $this->assertSame(25 * 60 - 1, $calculator->minutes($at('2026-10-25 00:00'), $at('2026-10-26 00:00'), $always));

        $this->assertNull(BusinessHours::fromArray(['hours' => [['day' => 'mon', 'start' => '17:00', 'end' => '08:00']]], 'UTC'));
    }

    public function test_the_aggregator_counts_messages_per_day_in_the_mailbox_time_zone(): void
    {
        $this->mailbox->update(['sla_minutes' => 60]);

        // 2026-09-15 in Europe/Berlin is 2026-09-14 22:00 – 2026-09-15 22:00 UTC.
        $a = $this->inbound('2026-09-14 22:30:00', ['from_address' => 'a@customer.test']);
        $b = $this->inbound('2026-09-15 07:00:00', ['from_address' => 'b@customer.test']);
        $c = $this->inbound('2026-09-15 07:10:00', ['from_address' => 'c@other.test']);
        $this->inbound('2026-09-15 08:00:00', ['from_address' => 'news@list.test', 'is_auto_generated' => true]);
        $this->inbound('2026-09-14 21:59:00'); // previous day
        $this->inbound('2026-09-15 22:00:00'); // next day
        // The same message in two folders counts once.
        $archive = MailboxFolder::factory()->create(['mailbox_id' => $this->mailbox->id]);
        MailboxMessage::factory()->create(['folder_id' => $archive->id, 'message_id' => $b->message_id, 'received_at' => '2026-09-15 07:00:00']);

        MailboxAttachment::factory()->create(['message_id' => $a->id, 'size' => 1000]);

        $linker = app(ReplyLinker::class);
        $linker->linkReply($this->reply($a, '2026-09-14 23:00:00'));   // 30 min
        $linker->linkReply($this->reply($b, '2026-09-15 09:00:00'));   // 120 min
        $linker->linkReply($this->reply($c, '2026-09-15 17:10:00'));   // 600 min

        $row = app(DailyStatsAggregator::class)->aggregate($this->mailbox, '2026-09-15');

        $this->assertSame(4, $row['inbound_count']);
        $this->assertSame(1, $row['auto_generated_count']);
        $this->assertSame(3, $row['outbound_count']);
        $this->assertSame(3, $row['replied_count']);
        $this->assertSame(120, $row['reply_minutes_p50']);
        $this->assertSame(600, $row['reply_minutes_p90']);
        $this->assertNull($row['reply_business_minutes_p50']);
        $this->assertSame(1, $row['sla_met_count']);
        $this->assertSame(2, $row['unique_sender_domains']);
        $this->assertSame(1000, $row['attachment_bytes_in']);

        $byHour = json_decode($row['inbound_by_hour'], true);
        $this->assertSame(1, $byHour[0]);  // 22:30 UTC = 00:30 Berlin
        $this->assertSame(2, $byHour[9]);  // 07:00 and 07:10 UTC
        $this->assertSame(1, $byHour[10]);

        $this->assertSame(
            ['customer.test' => 2, 'other.test' => 1],
            DB::table('mailbox_stats_domains_daily')->where('date', '2026-09-15')->orderByDesc('count')->pluck('count', 'domain')->map(fn ($count) => (int) $count)->all(),
        );

        // Idempotent.
        app(DailyStatsAggregator::class)->aggregate($this->mailbox, '2026-09-15');
        $this->assertSame(1, DB::table('mailbox_stats_daily')->count());
        $this->assertSame(2, DB::table('mailbox_stats_domains_daily')->count());
    }

    public function test_the_aggregate_command_handles_pending_days_and_ranges_and_backfill_links_replies(): void
    {
        DB::table('mailbox_stats_dirty_days')->insert(['mailbox_id' => $this->mailbox->id, 'date' => '2026-09-01']);

        $this->artisan('mailbox:stats-aggregate')->assertSuccessful();

        $this->assertSame(['2026-09-01', '2026-09-15', '2026-09-16'], DB::table('mailbox_stats_daily')->orderBy('date')->pluck('date')->map(fn ($date) => substr($date, 0, 10))->all());

        $this->artisan('mailbox:stats-aggregate', ['--from' => '2026-09-10', '--to' => '2026-09-12'])->assertSuccessful();
        $this->assertSame(6, DB::table('mailbox_stats_daily')->count());
        $this->artisan('mailbox:stats-aggregate', ['--date' => '15.09.2026'])->assertFailed();

        $inbound = $this->inbound('2026-09-10 08:00:00');
        $this->reply($inbound, '2026-09-10 08:45:00');

        $this->artisan('mailbox:stats-backfill', ['--days' => 10])->assertSuccessful();

        $this->assertSame(1, DB::table('mailbox_reply_links')->count());
        $this->assertSame(1, (int) DB::table('mailbox_stats_daily')->where('date', '2026-09-10')->value('replied_count'));

        config(['filament-mailbox.statistics.enabled' => false]);
        $this->artisan('mailbox:stats-aggregate')->expectsOutputToContain('disabled')->assertSuccessful();
    }

