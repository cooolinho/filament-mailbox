    public function test_live_statistics_age_unanswered_messages(): void
    {
        $this->inbound(now()->subHours(2)->toDateTimeString());
        $this->inbound(now()->subHours(30)->toDateTimeString(), ['is_read' => true]);
        $this->inbound(now()->subDays(5)->toDateTimeString());
        $this->inbound(now()->subDays(5)->toDateTimeString(), ['is_answered' => true]);
        $this->inbound(now()->subHour()->toDateTimeString(), ['is_auto_generated' => true]);
        $replied = $this->inbound(now()->subHours(3)->toDateTimeString());
        app(ReplyLinker::class)->linkReply($this->reply($replied, now()->toDateTimeString()));

        $live = app(LiveStatsProvider::class)->get([$this->mailbox->id]);

        $this->assertSame(['0_4h' => 1, '4_24h' => 0, '1_3d' => 1, 'over_3d' => 1], $live['unanswered']);
        $this->assertSame(5, $live['unread']);
        $this->assertGreaterThan(0, $live['storage_bytes']);
    }

    public function test_filters_are_limited_to_allowed_mailboxes(): void
    {
        $query = StatisticsQuery::fromFilters(['mailboxes' => [$this->mailbox->id, 999], 'period' => '7'], [$this->mailbox->id]);
        $this->assertSame([$this->mailbox->id], $query->mailboxIds);
        $this->assertSame('2026-09-10', $query->from->format('Y-m-d'));

        $query = StatisticsQuery::fromFilters(['mailboxes' => [999]], [$this->mailbox->id]);
        $this->assertSame([], $query->mailboxIds);

        $query = StatisticsQuery::fromFilters(['period' => 'custom', 'from' => '2026-09-12', 'until' => '2026-09-01'], [1]);
        $this->assertSame(['2026-09-01', '2026-09-12'], [$query->from->format('Y-m-d'), $query->until->format('Y-m-d')]);
        $this->assertSame(12, $query->days());
    }

    public function test_page_access_depends_on_role_and_configuration(): void
    {
        Livewire::test(MailboxStatistics::class)->assertSuccessful();

        app(MailboxAuthorization::class)->using(MailboxAuthorization::MANAGE, fn () => false);
        $this->assertFalse(MailboxStatistics::canAccess());
        $this->get(MailboxStatistics::getUrl())->assertForbidden();

        config(['filament-mailbox.statistics.visible_to' => 'assigned_users']);
        $other = Mailbox::factory()->create();
        $this->mailbox->users()->attach($this->user);

        $this->assertTrue(MailboxStatistics::canAccess());
        $this->assertSame([$this->mailbox->id], StatisticsSettings::allowedMailboxIds($this->user));
        $this->assertSame([$this->mailbox->id => 'Support'], MailboxStatistics::mailboxOptions());
        $this->assertNotContains($other->id, StatisticsSettings::allowedMailboxIds($this->user));

        config(['filament-mailbox.statistics.enabled' => false]);
        $this->assertFalse(MailboxStatistics::canAccess());
    }

    public function test_widgets_render_aggregates_and_ignore_foreign_mailboxes(): void
    {
        app(MailboxAuthorization::class)->using(MailboxAuthorization::MANAGE, fn () => false);
        config(['filament-mailbox.statistics.visible_to' => 'assigned_users']);
        $this->mailbox->users()->attach($this->user);
        $foreign = Mailbox::factory()->create(['name' => 'Secret']);

        $daily = fn (Mailbox $mailbox, int $inbound) => DB::table('mailbox_stats_daily')->insert([
            'mailbox_id' => $mailbox->id, 'date' => '2026-09-15', 'inbound_count' => $inbound, 'outbound_count' => 1,
            'inbound_by_hour' => json_encode(array_fill(0, 24, 0)), 'outbound_by_hour' => json_encode(array_fill(0, 24, 0)),
        ]);
        $daily($this->mailbox, 7);
        $daily($foreign, 500);
        DB::table('mailbox_stats_domains_daily')->insert([
            ['mailbox_id' => $this->mailbox->id, 'date' => '2026-09-15', 'domain' => 'customer.test', 'count' => 7],
            ['mailbox_id' => $foreign->id, 'date' => '2026-09-15', 'domain' => 'secret.test', 'count' => 500],
        ]);

        $filters = ['period' => '30', 'mailboxes' => [$foreign->id]];

        // A manipulated filter with a foreign mailbox shows nothing of it.
        Livewire::test(StatisticsOverviewWidget::class, ['pageFilters' => $filters])->assertDontSee('500');
        Livewire::test(TopDomainsWidget::class, ['pageFilters' => $filters])->assertDontSee('secret.test');

        Livewire::test(StatisticsOverviewWidget::class, ['pageFilters' => ['period' => '30']])->assertSee('7');
        Livewire::test(TopDomainsWidget::class, ['pageFilters' => ['period' => '30']])->assertSee('customer.test')->assertDontSee('secret.test');
        Livewire::test(UnansweredWidget::class, ['pageFilters' => []])->assertSee('Support')->assertDontSee('Secret');
        Livewire::test(VolumeChartWidget::class, ['pageFilters' => []])->assertSuccessful();

        $response = Livewire::test(MailboxStatistics::class)
            ->set('filters', ['period' => '30', 'mailboxes' => [$foreign->id, $this->mailbox->id]])
            ->instance()
            ->export();

        ob_start();
        $response->sendContent();
        $csv = ob_get_clean();

        $this->assertStringContainsString('2026-09-15,'.$this->mailbox->id.',Support,7,1', $csv);
        $this->assertStringNotContainsString('Secret', $csv);
    }

    public function test_business_hours_and_sla_are_saved_with_the_mailbox(): void
    {
        Livewire::test(EditMailbox::class, ['record' => $this->mailbox->getRouteKey()])
            ->fillForm([
                'password' => '',
                'sla_minutes' => 120,
                'business_hours' => [
                    'timezone' => 'Europe/Vienna',
                    'hours' => [['day' => 'mon', 'start' => '08:00', 'end' => '16:00']],
                    'holidays' => ['2026-12-24'],
                ],
            ])
            ->call('save')
            ->assertHasNoFormErrors();

        $mailbox = $this->mailbox->fresh();
        $this->assertSame(120, $mailbox->sla_minutes);
        $this->assertSame('Europe/Vienna', BusinessHours::timezoneFor($mailbox));
        $this->assertSame(['mon' => [['08:00', '16:00']]], BusinessHours::forMailbox($mailbox)->intervals);
        $this->assertSame(['2026-12-24'], BusinessHours::forMailbox($mailbox)->holidays);
    }
